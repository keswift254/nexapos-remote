/// Text-only ESC/POS report for the configured thermal printer. The PDF stays
/// available for export, but sending a narrow PDF through a printer driver can
/// rasterize it faintly or clip it to the wrong paper width.
Future<Uint8List> buildThermalReport({
  required ReportData data,
  required String reportTitle,
  required String periodLabel,
  required bool isMonthlyReport,
  required DateFormat timeFormat,
  required BusinessSettings settings,
  required String generatedByName,
}) async {
  final isNarrow = settings.paperWidthMm <= 58;
  final columns = isNarrow ? 32 : 48;
  final profile = await CapabilityProfile.load();
  final generator = Generator(
    isNarrow ? PaperSize.mm58 : PaperSize.mm80,
    profile,
  );
  final bytes = <int>[];
  final currency = settings.currency;
  String money(int cents) => Money(cents).format(currency: currency);

  void text(String value, {bool bold = false, PosAlign align = PosAlign.left}) {
    for (final line in wrapThermalLine(value, columns)) {
      bytes.addAll(
        generator.text(
          line,
          styles: PosStyles(bold: bold, align: align),
        ),
      );
    }
  }

  void pair(String label, String value, {bool bold = false}) {
    final remaining = columns - label.length - value.length;
    if (remaining >= 1) {
      text('$label${' ' * remaining}$value', bold: bold);
    } else {
      text(label, bold: bold);
      text(value, bold: bold, align: PosAlign.right);
    }
  }

  void divider() => bytes.addAll(generator.hr());

  text(settings.businessName.toUpperCase(), bold: true, align: PosAlign.center);
  text(reportTitle.toUpperCase(), bold: true, align: PosAlign.center);
  text(periodLabel.toUpperCase(), align: PosAlign.center);
  divider();
  text('SALES', bold: true);
  if (data.sales.isEmpty) text('No paid sales');
  for (final sale in data.sales) {
    pair(
      timeFormat.format(DateTime.parse(sale.createdAt).toLocal()),
      money(sale.totalCents),
    );
    text(sale.itemNames ?? sale.saleNumber);
  }
  divider();
  pair('Total Paid Sales', money(data.salesTotal.cents), bold: true);
  pair('Cash Received', money(data.cashReceivedTotal.cents));
  pair('Paid by M-Pesa', money(data.mpesaTotal.cents));
  divider();
  text('EXPENSES', bold: true);
  if (data.expenses.isEmpty) text('No expenses');
  for (final expense in data.expenses) {
    pair(
      timeFormat.format(DateTime.parse(expense.createdAt).toLocal()),
      money(expense.amountCents),
    );
    text(expense.title);
  }
  divider();
  pair('Total Expenses', money(data.expensesTotal.cents), bold: true);
  if (isMonthlyReport) pair('Gross Profit', money(data.grossProfitTotal.cents));
  divider();
  pair(
    isMonthlyReport ? 'NET PROFIT' : 'GRAND TOTAL',
    money((isMonthlyReport ? data.netProfit : data.grandTotal).cents),
    bold: true,
  );
  divider();
  text('Cashier/Admin: $generatedByName');
  text('Report Date: $periodLabel');
  text('Generated: ${DateFormat('d MMM yyyy HH:mm').format(DateTime.now())}');
  text('Generated by NexaPOS', bold: true, align: PosAlign.center);
  text('Thank you for using NexaPOS', align: PosAlign.center);
  text(supportFooter, align: PosAlign.center);
  bytes.addAll(generator.feed(3));
  bytes.addAll(generator.cut());
  return Uint8List.fromList(bytes);
}

/// Keeps long item names and amounts inside the printable character width.
List<String> wrapThermalLine(String value, int columns) {
  final words = value.trim().split(RegExp(r'\s+'));
  final lines = <String>[];
  var current = '';
  for (final word in words) {
    if (word.isEmpty) continue;
    var remaining = word;
    while (remaining.isNotEmpty) {
      final available = columns - current.length - (current.isEmpty ? 0 : 1);
      if (available <= 0) {
        lines.add(current);
        current = '';
        continue;
      }
      if (remaining.length <= available) {
        current = current.isEmpty ? remaining : '$current $remaining';
        remaining = '';
      } else if (current.isNotEmpty) {
        lines.add(current);
        current = '';
      } else {
        lines.add(remaining.substring(0, columns));
        remaining = remaining.substring(columns);
      }
    }
  }
  if (current.isNotEmpty) lines.add(current);
  return lines.isEmpty ? [''] : lines;
}
